    private void btnBFSActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBFSActionPerformed
        if (grafo == null || grafo.getNumNeuronas() == 0) {
            JOptionPane.showMessageDialog(this, "Primero debe cargar una red neuronal.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        String input = JOptionPane.showInputDialog(this, "Ingrese el ID de la neurona origen:", "Detectar Zonas Aisladas", JOptionPane.QUESTION_MESSAGE);
        if (input == null || input.trim().isEmpty()) {
            return;
        }
        
        try {
            int idOrigen = Integer.parseInt(input.trim());
            
            if (grafo.obtenerNeurona(idOrigen) == null) {
                JOptionPane.showMessageDialog(this, "La neurona con ID " + idOrigen + " no existe.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            // Convertir grafo al formato esperado por BFS
            TablaHash<Integer, ListaEnlazada<Integer>> grafoBFS = convertirGrafoParaBFS();
            
            // Ejecutar BFS
            ListaEnlazada<Integer> zonasAisladas = BFS.obtenerZonasAisladas(grafoBFS, idOrigen);
            
            // Resaltar zonas aisladas en el panel
            panelGrafo.resaltarZonasAisladas(zonasAisladas);
            
            // Mostrar resultados
            StringBuilder resultado = new StringBuilder();
            resultado.append("=== RESULTADOS BFS ===\n");
            resultado.append("Neurona origen: ").append(idOrigen).append("\n");
            resultado.append("Zonas aisladas detectadas: ").append(zonasAisladas.getTamaño()).append("\n");
            
            if (zonasAisladas.getTamaño() > 0) {
                resultado.append("IDs de neuronas aisladas:\n");
                for (int i = 0; i < zonasAisladas.getTamaño(); i++) {
                    resultado.append("  - ").append(zonasAisladas.obtener(i)).append("\n");
                }
            } else {
                resultado.append("No hay zonas aisladas. Todas las neuronas son alcanzables desde el origen.\n");
            }
            
            txtResultados.setText(resultado.toString());
            JOptionPane.showMessageDialog(this, resultado.toString(), "Resultado BFS", JOptionPane.INFORMATION_MESSAGE);
            
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Debe ingresar un número válido para el ID de la neurona.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnBFSActionPerformed
    
    private void CargarCSVsinapsisActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CargarCSVsinapsisActionPerformed
        javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();
        fileChooser.setDialogTitle("Seleccionar archivo CSV de red neuronal");
        
        int resultado = fileChooser.showOpenDialog(this);
        if (resultado == javax.swing.JFileChooser.APPROVE_OPTION) {
            String rutaArchivo = fileChooser.getSelectedFile().getAbsolutePath();
            
            try {
                // Leer archivo CSV
                ListaEnlazada<String[]> datos = CargadorCSV.leerArchivo(rutaArchivo, true);
                
                if (datos.getTamaño() == 0) {
                    JOptionPane.showMessageDialog(this, "El archivo está vacío o no tiene datos válidos.", "Error", JOptionPane.ERROR_MESSAGE);
                    return;
                }
                
                // Limpiar grafo actual
                grafo = new Grafo();
                
                // Procesar datos y crear grafo
                for (int i = 0; i < datos.getTamaño(); i++) {
                    String[] fila = datos.obtener(i);
                    
                    // Formato esperado: idOrigen, idDestino, distancia, idNeurotransmisor, coeficienteEficiencia
                    if (fila.length >= 5) {
                        int idOrigen = Integer.parseInt(fila[0]);
                        int idDestino = Integer.parseInt(fila[1]);
                        double distancia = Double.parseDouble(fila[2]);
                        String idNeuro = fila[3];
                        double coeficiente = Double.parseDouble(fila[4]);
                        
                        // Crear neuronas si no existen
                        if (grafo.obtenerNeurona(idOrigen) == null) {
                            grafo.agregarNeurona(new Neurona(idOrigen));
                        }
                        if (grafo.obtenerNeurona(idDestino) == null) {
                            grafo.agregarNeurona(new Neurona(idDestino));
                        }
                        
                        // Crear sinapsis
                        Neurona origen = grafo.obtenerNeurona(idOrigen);
                        Neurona destino = grafo.obtenerNeurona(idDestino);
                        Sinapsis sinapsis = new Sinapsis(origen, destino, distancia, idNeuro, coeficiente);
                        grafo.agregarSinapsis(sinapsis);
                    }
                }
                
                // Actualizar visualización
                panelGrafo.actualizarGrafo(grafo);
                
                JOptionPane.showMessageDialog(this, 
                    "Red neuronal cargada exitosamente.\n" +
                    "Neuronas: " + grafo.getNumNeuronas() + "\n" +
                    "Sinapsis: " + grafo.getNumSinapsis(), 
                    "Éxito", JOptionPane.INFORMATION_MESSAGE);
                    
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Error al cargar el archivo: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_CargarCSVsinapsisActionPerformed
    
