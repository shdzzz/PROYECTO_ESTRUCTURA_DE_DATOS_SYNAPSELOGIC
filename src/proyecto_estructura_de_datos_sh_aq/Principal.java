    private void btnDijkstraActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDijkstraActionPerformed
        if (grafo == null || grafo.getNumNeuronas() == 0) {
            JOptionPane.showMessageDialog(this, "Primero debe cargar una red neuronal.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        String inputOrigen = JOptionPane.showInputDialog(this, "Ingrese el ID de la neurona origen:", "Calcular Ruta Más Rápida", JOptionPane.QUESTION_MESSAGE);
        if (inputOrigen == null || inputOrigen.trim().isEmpty()) {
            return;
        }
        
        String inputDestino = JOptionPane.showInputDialog(this, "Ingrese el ID de la neurona destino:", "Calcular Ruta Más Rápida", JOptionPane.QUESTION_MESSAGE);
        if (inputDestino == null || inputDestino.trim().isEmpty()) {
            return;
        }
        
        try {
            int idOrigen = Integer.parseInt(inputOrigen.trim());
            int idDestino = Integer.parseInt(inputDestino.trim());
            
            if (grafo.obtenerNeurona(idOrigen) == null) {
                JOptionPane.showMessageDialog(this, "La neurona origen con ID " + idOrigen + " no existe.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            if (grafo.obtenerNeurona(idDestino) == null) {
                JOptionPane.showMessageDialog(this, "La neurona destino con ID " + idDestino + " no existe.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            // Ejecutar Dijkstra
            Dijkstra.ResultadoDijkstra resultado = Dijkstra.buscar(
                grafo.getAdyacencia(), 
                grafo.getDiccionarioNeuro(), 
                idOrigen
            );
            
            // Reconstruir camino
            ListaEnlazada<Integer> camino = Dijkstra.reconstruirCamino(resultado, idDestino);
            double distancia = obtenerDistancia(resultado, idDestino);
            
            // Mostrar resultados
            StringBuilder resultadoStr = new StringBuilder();
            resultadoStr.append("=== RESULTADO DIJKSTRA ===\n");
            resultadoStr.append("Origen: ").append(idOrigen).append("\n");
            resultadoStr.append("Destino: ").append(idDestino).append("\n");
            
            if (distancia == Double.MAX_VALUE || camino.getTamaño() <= 1) {
                resultadoStr.append("No existe camino entre las neuronas.\n");
            } else {
                resultadoStr.append("Distancia total: ").append(String.format("%.2f", distancia)).append("\n");
                resultadoStr.append("Camino: ");
                for (int i = 0; i < camino.getTamaño(); i++) {
                    resultadoStr.append(camino.obtener(i));
                    if (i < camino.getTamaño() - 1) {
                        resultadoStr.append(" -> ");
                    }
                }
                resultadoStr.append("\n");
            }
            
            txtResultados.setText(resultadoStr.toString());
            JOptionPane.showMessageDialog(this, resultadoStr.toString(), "Resultado Dijkstra", JOptionPane.INFORMATION_MESSAGE);
            
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Debe ingresar números válidos para los IDs de las neuronas.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnDijkstraActionPerformed
    
    private void btnFatigaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFatigaActionPerformed
        if (grafo == null || grafo.getNumSinapsis() == 0) {
            JOptionPane.showMessageDialog(this, "Primero debe cargar una red neuronal.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        int confirmacion = JOptionPane.showConfirmDialog(this, 
            "¿Está seguro que desea simular fatiga?\nEsto multiplicará el coeficiente de eficiencia de todas las sinapsis por 1.2.", 
            "Confirmar simulación de fatiga", 
            JOptionPane.YES_NO_OPTION, 
            JOptionPane.QUESTION_MESSAGE);
            
        if (confirmacion == JOptionPane.YES_OPTION) {
            // Multiplicar coeficiente de eficiencia por 1.2
            TablaHash<Integer, ListaEnlazada<Sinapsis>> adyacencia = grafo.getAdyacencia();
            Object[] claves = adyacencia.getClaves();
            
            for (Object clave : claves) {
                Integer id = (Integer) clave;
                ListaEnlazada<Sinapsis> sinapsis = adyacencia.obtener(id);
                
                if (sinapsis != null) {
                    for (int i = 0; i < sinapsis.getTamaño(); i++) {
                        Sinapsis s = sinapsis.obtener(i);
                        double nuevoCoeficiente = s.getCoeficienteEficiencia() * 1.2;
                        s.setCoeficienteEficiencia(nuevoCoeficiente);
                    }
                }
            }
            
            // Actualizar visualización
            panelGrafo.actualizarGrafo(grafo);
            
            JOptionPane.showMessageDialog(this, 
                "Simulación de fatiga completada exitosamente.\n" +
                "El coeficiente de eficiencia de todas las sinapsis ha sido multiplicado por 1.2.", 
                "Éxito", JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_btnFatigaActionPerformed
    
