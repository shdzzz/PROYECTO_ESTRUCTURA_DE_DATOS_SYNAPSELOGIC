    /**
     * Convierte el grafo del proyecto al formato esperado por BFS.
     * @return TablaHash con IDs de neuronas y listas de IDs de vecinos
     */
    private TablaHash<Integer, ListaEnlazada<Integer>> convertirGrafoParaBFS() {
        TablaHash<Integer, ListaEnlazada<Integer>> grafoBFS = new TablaHash<>();
        TablaHash<Integer, ListaEnlazada<Sinapsis>> adyacencia = grafo.getAdyacencia();
        Object[] claves = adyacencia.getClaves();
        
        for (Object clave : claves) {
            Integer id = (Integer) clave;
            ListaEnlazada<Sinapsis> sinapsis = adyacencia.obtener(id);
            ListaEnlazada<Integer> vecinos = new ListaEnlazada<>();
            
            if (sinapsis != null) {
                for (int i = 0; i < sinapsis.getTamaño(); i++) {
                    Sinapsis s = sinapsis.obtener(i);
                    if (s != null && s.getDestino() != null) {
                        vecinos.agregar(s.getDestino().getId());
                    }
                }
            }
            grafoBFS.insertar(id, vecinos);
        }
        
        return grafoBFS;
    }
    
    /**
     * Obtiene la distancia desde el origen hasta un destino específico.
     * @param resultado Resultado de Dijkstra
     * @param idDestino ID de la neurona destino
     * @return Distancia calculada o Double.MAX_VALUE si no existe camino
     */
    private double obtenerDistancia(Dijkstra.ResultadoDijkstra resultado, int idDestino) {
        Double distancia = resultado.distancias.obtener(idDestino);
        return distancia != null ? distancia : Double.MAX_VALUE;
    }

